CREATE TABLE IF NOT EXISTS live_predictions (
    id BIGSERIAL PRIMARY KEY,
    prediction_id VARCHAR(64) NOT NULL,
    semantic_sha256 VARCHAR(64) NOT NULL,
    prediction_version VARCHAR(64) NOT NULL,
    live_input_version VARCHAR(64) NOT NULL,
    condition_id TEXT NOT NULL,
    slug VARCHAR(256) NOT NULL,
    horizon_seconds INTEGER NOT NULL,
    market_start_at TIMESTAMPTZ NOT NULL,
    market_end_at TIMESTAMPTZ NOT NULL,
    scheduled_at TIMESTAMPTZ NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL,
    lateness_ms INTEGER NOT NULL,
    up_token_id TEXT NOT NULL,
    down_token_id TEXT NOT NULL,
    source_calibration_run_id VARCHAR(128) NOT NULL,
    source_calibration_semantic_sha256 VARCHAR(64) NOT NULL,
    source_backtest_run_id VARCHAR(128) NOT NULL,
    source_backtest_semantic_sha256 VARCHAR(64) NOT NULL,
    source_training_run_id VARCHAR(128) NOT NULL,
    source_training_semantic_sha256 VARCHAR(64) NOT NULL,
    calibration_version VARCHAR(64) NOT NULL,
    edge_policy_version VARCHAR(64) NOT NULL,
    source_feature_version VARCHAR(64) NOT NULL,
    source_label_version VARCHAR(64) NOT NULL,
    selected_offset_seconds INTEGER NOT NULL,
    policy_sha256 VARCHAR(64) NOT NULL,
    calibration_fit JSONB NOT NULL,
    calibration_fit_sha256 VARCHAR(64) NOT NULL,
    edge_config JSONB NOT NULL,
    edge_config_sha256 VARCHAR(64) NOT NULL,
    edge_policy VARCHAR(32) NOT NULL,
    min_edge NUMERIC(38, 18),
    training_prior NUMERIC(38, 18) NOT NULL,
    raw_probability NUMERIC(38, 18) NOT NULL,
    calibrated_probability NUMERIC(38, 18) NOT NULL,
    predicted_target INTEGER NOT NULL,
    predicted_side VARCHAR(8) NOT NULL,
    market_probability_observed BOOLEAN NOT NULL,
    market_probability NUMERIC(38, 18),
    market_probability_observed_at TIMESTAMPTZ,
    market_probability_downloaded_at TIMESTAMPTZ NOT NULL,
    market_probability_source VARCHAR(64) NOT NULL,
    market_probability_dataset VARCHAR(64) NOT NULL,
    market_probability_request_params JSONB NOT NULL,
    market_probability_response_sha256 VARCHAR(64) NOT NULL,
    up_best_bid NUMERIC(38, 18),
    up_best_ask NUMERIC(38, 18),
    up_book_cutoff_at TIMESTAMPTZ,
    up_book_fresh BOOLEAN NOT NULL,
    down_best_bid NUMERIC(38, 18),
    down_best_ask NUMERIC(38, 18),
    down_book_cutoff_at TIMESTAMPTZ,
    down_book_fresh BOOLEAN NOT NULL,
    selected_side VARCHAR(8) NOT NULL,
    executable BOOLEAN NOT NULL,
    trade BOOLEAN NOT NULL,
    decision_reason VARCHAR(64) NOT NULL,
    selected_ask NUMERIC(38, 18),
    selected_bid NUMERIC(38, 18),
    selected_spread NUMERIC(38, 18),
    fee NUMERIC(38, 18) NOT NULL,
    slippage_buffer NUMERIC(38, 18) NOT NULL,
    raw_edge NUMERIC(38, 18),
    cost_adjusted_edge NUMERIC(38, 18),
    decision_min_edge NUMERIC(38, 18),
    edge_decision JSONB NOT NULL,
    input_fingerprint VARCHAR(64) NOT NULL,
    CONSTRAINT ck_live_predictions_positive_horizon CHECK (horizon_seconds > 0),
    CONSTRAINT ck_live_predictions_window_order CHECK (market_end_at > market_start_at),
    CONSTRAINT ck_live_predictions_schedule_after_start CHECK (scheduled_at > market_start_at),
    CONSTRAINT ck_live_predictions_schedule_before_end CHECK (scheduled_at < market_end_at),
    CONSTRAINT ck_live_predictions_lateness CHECK (lateness_ms >= 0 AND lateness_ms <= 10000),
    CONSTRAINT uq_live_predictions_prediction_id UNIQUE (prediction_id),
    CONSTRAINT uq_live_predictions_condition_version UNIQUE (condition_id, prediction_version)
);

CREATE INDEX IF NOT EXISTS ix_live_predictions_scheduled_at
    ON live_predictions (scheduled_at);
CREATE INDEX IF NOT EXISTS ix_live_predictions_horizon_scheduled
    ON live_predictions (horizon_seconds, scheduled_at);

CREATE TABLE IF NOT EXISTS live_prediction_evaluations (
    id BIGSERIAL PRIMARY KEY,
    prediction_id VARCHAR(64) NOT NULL,
    label_version VARCHAR(64) NOT NULL,
    official_outcome VARCHAR(8) NOT NULL,
    official_target INTEGER NOT NULL,
    label_source VARCHAR(64) NOT NULL,
    label_source_snapshot_sha256 VARCHAR(64) NOT NULL,
    label_source_observed_at TIMESTAMPTZ NOT NULL,
    evaluated_at TIMESTAMPTZ NOT NULL,
    correct BOOLEAN NOT NULL,
    raw_log_loss NUMERIC(38, 18) NOT NULL,
    raw_brier NUMERIC(38, 18) NOT NULL,
    calibrated_log_loss NUMERIC(38, 18) NOT NULL,
    calibrated_brier NUMERIC(38, 18) NOT NULL,
    hypothetical_gross_pnl NUMERIC(38, 18),
    hypothetical_assumed_cost_pnl NUMERIC(38, 18),
    semantic_sha256 VARCHAR(64) NOT NULL,
    CONSTRAINT ck_live_prediction_evaluations_target CHECK (official_target IN (0, 1)),
    CONSTRAINT uq_live_prediction_evaluations_prediction_label UNIQUE (prediction_id, label_version)
);

CREATE INDEX IF NOT EXISTS ix_live_prediction_evaluations_evaluated_at
    ON live_prediction_evaluations (evaluated_at);
